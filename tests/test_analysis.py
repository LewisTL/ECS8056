def test_determinism_check_passes_on_identical_repeats():
    log = synthetic_log("grounded", n=5)
    doubled = pd.concat([log, log], ignore_index=True)
    assert determinism_check(doubled)["deterministic"]


def test_determinism_check_catches_a_disagreeing_repeat():
    log = synthetic_log("grounded", n=5)
    drifted = log.copy()
    drifted.loc[drifted.index[0], "c0"] += 1e-6
    doubled = pd.concat([log, drifted], ignore_index=True)
    result = determinism_check(doubled)
    assert not result["deterministic"]
    assert result["max_spread"] > 0
