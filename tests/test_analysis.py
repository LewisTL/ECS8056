"""
tests/test_analysis.py: unit tests for the probe statistics in analysis.py.

The central test is that the battery discriminates the three accounts the study
must tell apart, using synthetic logs generated from each:

  * `grounded`: the action follows the scene, and the term selects which target.
  * `lexical`: the term fixes the direction and the image plays no part.
  * `blind`: the output ignores instruction and image alike.

A `lexical` model reproduces the antonym sign flip perfectly, so it passes the
original sign-flip metric. Confirming that the controls separate it from
`grounded` is what justifies the rebuild, and a regression there would silently
restore the ambiguity the earlier design suffered from.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

from analysis import (
    absolute_congruence,
    axis_value,
    congruence_test,
    determinism_check,
    lexical_check,
    mirror_check,
    mirror_check_by_configuration,
    resolution_report,
    same_side_test,
    term_effect,
    tost_equivalence,
    value_column,
    wilcoxon_paired,
)

BIN_WIDTH = 0.001118


def _row(scene_id, condition, role, value, axis_index=0, configuration="opposite",
         expected_sign_image=-1, target_sign_a_image=-1, target_sign_b_image=1,
         base_scene_id="f0", spatial_term="left"):
    row = {
        "scene_id": scene_id, "condition": condition, "role": role,
        "axis_index": axis_index, "configuration": configuration,
        "base_scene_id": base_scene_id, "spatial_term": spatial_term,
        "expected_sign_image": expected_sign_image,
        "target_sign_a_image": target_sign_a_image,
        "target_sign_b_image": target_sign_b_image,
        "instruction": f"{scene_id}-{role}-{condition}",
    }
    for i in range(7):
        row[f"c{i}"] = value if i == axis_index else 0.0
        row[f"a{i}"] = value if i == axis_index else 0.0
    return row


def synthetic_log(model, n=40, seed=0, scale=0.01):
    """A prediction log generated by one of the three accounts.

    Geometry is expressed the way the probe logs it: image coordinates in which a
    negative sign is further left in the frame, with role `a` always carrying the
    term `left`. Consecutive scenes share a base frame and take the two
    arrangements, matching the frozen evaluation set, so the paired form of the
    decisive contrast has something to pair.

    `scale` sets the magnitude of every prediction, which is what the magnitude
    floor is read against.
    """
    rng = np.random.default_rng(seed)
    rows = []
    for s in range(n):
        configuration = "opposite" if s % 2 == 0 else "same_side_left"
        # Where each instruction's target sits, relative to the start position.
        # In the same-side arrangement both lie in the same direction, which is
        # the condition that separates the grounded and lexical accounts, and it
        # is also the arrangement whose `right` instruction is incongruent with
        # the side its own target occupies.
        if configuration == "opposite":
            target_a, target_b = -1.0, 1.0
        else:
            target_a, target_b = -1.0, -0.4
        scene = f"s{s}"

        def value(role, target, mirrored=False, no_referent=False):
            if model == "grounded":
                # The term-free instruction still reaches for the object, which
                # is the object-grounding baseline the mirror control reads.
                base = target_a if role == "n" else target
                if no_referent:
                    base = rng.choice([-1.0, 1.0]) * 0.05
                return -base if mirrored else base
            if model == "lexical":
                # The word fixes the direction; the scene plays no part, so
                # mirroring changes nothing.
                return {"a": -1.0, "b": 1.0, "n": 0.0}[role]
            return 0.0

        def row(condition, role, val):
            return _row(scene, condition, role, val * scale,
                        configuration=configuration,
                        base_scene_id=f"f{s // 2}",
                        expected_sign_image=int(np.sign(target_a - target_b)),
                        target_sign_a_image=int(np.sign(target_a)),
                        target_sign_b_image=int(np.sign(target_b)))

        for role, target in (("a", target_a), ("b", target_b)):
            rows.append(row("baseline", role, value(role, target)))
            rows.append(row("swapped_scene", role,
                            value(role, target, no_referent=True)))
            rows.append(row("mirror", role, value(role, target, mirrored=True)))
        rows.append(row("neutral", "n", value("n", target_a)))
        rows.append(row("mirror_neutral", "n", value("n", target_a, mirrored=True)))
    return pd.DataFrame(rows)


